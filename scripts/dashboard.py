#!/usr/bin/env python3
"""Benchmark dashboard — compare downscaling methods.

Run with:
    pip install streamlit plotly
    streamlit run scripts/dashboard.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
import plotly.graph_objects as go
import streamlit as st

ROOT = Path(__file__).parent.parent
RESULTS_DIR = ROOT / "results"

# Display labels for result directory names
METHOD_LABELS = {
    "bicubic":     "Bicubic",
    "bcsd":        "BCSD",
    "gnn":         "PSM",         # Perfect Model Setting
    "psm":         "PSM",
    "consistency": "CM",          # Consistency Model
    "cm":          "CM",
    "serpentflow": "SF",          # SerpentFlow
    "sf":          "SF",
}
COLORS = ["#1f77b4", "#ff7f0e", "#2ca02c", "#d62728", "#9467bd", "#8c564b"]

st.set_page_config(page_title="Downscaling Benchmark", layout="wide")
st.title("Downscaling Benchmark Dashboard")

# ── Discover methods ──────────────────────────────────────────────────────────
all_method_dirs = sorted(
    d.name for d in RESULTS_DIR.iterdir()
    if d.is_dir() and (d / "metrics.json").exists()
) if RESULTS_DIR.exists() else []

if not all_method_dirs:
    st.error(f"No method results found in {RESULTS_DIR}")
    st.stop()

raw_metrics: dict[str, dict] = {}
for m in all_method_dirs:
    with open(RESULTS_DIR / m / "metrics.json") as f:
        raw_metrics[m] = json.load(f)

# Load plot_data.json if available (generated by updated evaluate.py)
plot_data: dict[str, dict] = {}
for m in all_method_dirs:
    pf = RESULTS_DIR / m / "plot_data.json"
    if pf.exists():
        with open(pf) as f:
            plot_data[m] = json.load(f)

def mlabel(m: str) -> str:
    return METHOD_LABELS.get(m, m.upper())

def _method_color(m: str) -> str:
    return COLORS[list(all_method_dirs).index(m) % len(COLORS)]

# ── Sidebar ───────────────────────────────────────────────────────────────────
with st.sidebar:
    st.header("Filters")
    sel_methods = st.multiselect(
        "Methods", all_method_dirs, default=all_method_dirs,
        format_func=mlabel, key="methods",
    )
    if not sel_methods:
        st.warning("Select at least one method.")
        st.stop()

    all_vars = [v for v in next(iter(raw_metrics.values())).keys()
                if not v.startswith("_")]
    sel_vars = st.multiselect("Variables", all_vars, default=all_vars, key="vars")

    st.markdown("---")
    st.caption(
        "**ERA5**: pseudo-obs (1960–2020)  \n"
        "**GCM**: IPSL-CM6A-LR (historical + ssp585)  \n"
        "Evaluation period: 2004–2014"
    )

# ── Metric groups ─────────────────────────────────────────────────────────────
OBS_METRICS = [
    "bias_mae", "std_error",
    "ks_full", "ks_q95", "ks_q05",
    "seasonal_mae", "extreme_freq", "extreme_intensity",
    "spectral_mae",
]
GCM_METRICS = [
    "temporal_corr_annual", "temporal_corr",
    "annual_anomaly_bias", "lag1_autocorr_mae",
]

METRIC_LABELS = {
    "bias_mae":             "Bias MAE (vs ERA5)",
    "std_error":            "Std error (vs ERA5)",
    "ks_full":              "KS full dist (vs ERA5)",
    "ks_q95":               "KS upper tail q>0.95",
    "ks_q05":               "KS lower tail q<0.05",
    "seasonal_mae":         "Seasonal MAE (vs ERA5)",
    "extreme_freq":         "Extreme freq bias",
    "extreme_intensity":    "Extreme intensity bias",
    "spectral_mae":         "Spectral MAE (vs ERA5)",
    "temporal_corr_annual": "Temporal corr annual (vs GCM)",
    "temporal_corr":        "Temporal corr daily (vs GCM)",
    "annual_anomaly_bias":  "Annual anomaly bias (vs GCM)",
    "lag1_autocorr_mae":    "Lag-1 autocorr MAE (vs GCM)",
}
HIGHER_BETTER = {"temporal_corr_annual", "temporal_corr"}

# ── Helpers ───────────────────────────────────────────────────────────────────
def _agg(method: str, key: str, axis: str = "vs_obs") -> float:
    vals = [
        raw_metrics[method][v][axis][key]
        for v in sel_vars
        if v in raw_metrics[method] and key in raw_metrics[method][v].get(axis, {})
    ]
    return float(np.nanmean(vals)) if vals else float("nan")

# ── Tabs ──────────────────────────────────────────────────────────────────────
tab_table, tab_radar, tab_lines, tab_maps, tab_intervar = st.tabs([
    "📊 Metrics table", "🕸 Radar", "📈 Line plots", "🗺 Spatial maps", "🔗 Inter-variable",
])

# ══════════════════════════════════════════════════════════════════════════════
# Tab 1 — Metrics table (pivot: one column per method, highlight best)
# ══════════════════════════════════════════════════════════════════════════════
with tab_table:
    col_l, col_r = st.columns([3, 1])
    with col_l:
        show_obs = st.multiselect(
            "vs ERA5 metrics", OBS_METRICS,
            default=["bias_mae", "std_error", "ks_full", "seasonal_mae", "spectral_mae"],
            format_func=lambda k: METRIC_LABELS.get(k, k),
        )
    with col_r:
        show_gcm = st.multiselect(
            "vs GCM metrics", GCM_METRICS,
            default=["temporal_corr_annual", "annual_anomaly_bias"],
            format_func=lambda k: METRIC_LABELS.get(k, k),
        )

    rows = []
    key_list: list[str] = []
    for var in sel_vars:
        for k in show_obs:
            row = {"Variable": var, "Metric": METRIC_LABELS.get(k, k)}
            for m in sel_methods:
                row[mlabel(m)] = raw_metrics[m].get(var, {}).get("vs_obs", {}).get(k, float("nan"))
            rows.append(row)
            key_list.append(k)
        for k in show_gcm:
            row = {"Variable": var, "Metric": METRIC_LABELS.get(k, k)}
            for m in sel_methods:
                row[mlabel(m)] = raw_metrics[m].get(var, {}).get("vs_gcm", {}).get(k, float("nan"))
            rows.append(row)
            key_list.append(k)

    if rows:
        df = pd.DataFrame(rows).set_index(["Variable", "Metric"])
        method_cols_present = [mlabel(m) for m in sel_methods if mlabel(m) in df.columns]

        def _style_row(row: pd.Series) -> list[str]:
            pos = list(df.index).index(row.name)
            key = key_list[pos]
            vals = pd.to_numeric(row, errors="coerce")
            is_higher = key in HIGHER_BETTER
            best = vals.idxmax() if is_higher else vals.idxmin()
            styles = [""] * len(row)
            if pd.notna(best) and best in row.index:
                styles[list(row.index).index(best)] = (
                    "background-color: #c6efce; color: #276221; font-weight: bold"
                )
            return styles

        styled = df.style.apply(_style_row, axis=1).format("{:.4f}", na_rep="—")
        st.dataframe(styled, use_container_width=True)
        st.caption(
            "One column per method — green = best per row. "
            "All metrics lower-is-better except temporal corr (higher = better).  \n"
            "**Temporal corr daily ≈ 1 everywhere**: all methods are deterministic "
            "functions of the GCM, so daily correlation with GCM input is trivially ~1. "
            "Use *temporal corr annual* instead.  \n"
            "**BCSD high annual anomaly bias (psl)**: per-month QM + spatial disaggregation "
            "distorts the year-to-year evolution of large-scale fields like psl. "
            "BCSD is designed for climatological bias correction, not signal preservation."
        )
    else:
        st.info("No data for the selected filters.")

# ══════════════════════════════════════════════════════════════════════════════
# Tab 2 — Radar
# ══════════════════════════════════════════════════════════════════════════════
with tab_radar:
    radar_obs_keys = st.multiselect(
        "vs ERA5 metrics on radar", OBS_METRICS,
        default=["bias_mae", "std_error", "ks_full", "seasonal_mae", "extreme_intensity", "spectral_mae"],
        format_func=lambda k: METRIC_LABELS.get(k, k),
        key="radar_obs",
    )
    radar_gcm_keys = st.multiselect(
        "vs GCM metrics on radar", GCM_METRICS,
        default=["temporal_corr_annual"],
        format_func=lambda k: METRIC_LABELS.get(k, k),
        key="radar_gcm",
    )
    radar_keys = radar_obs_keys + radar_gcm_keys

    if len(radar_keys) < 3:
        st.info("Select at least 3 metrics for a radar plot.")
    else:
        def _get_val(method: str, key: str) -> float:
            axis = "vs_obs" if key in OBS_METRICS else "vs_gcm"
            v = _agg(method, key, axis)
            return (1 - v) if key in HIGHER_BETTER else v

        norm_base = {}
        for k in radar_keys:
            vals = [_get_val(m, k) for m in sel_methods]
            finite = [v for v in vals if np.isfinite(v)]
            norm_base[k] = float(np.nanmean(finite)) if finite else 1.0

        fig = go.Figure()
        theta = [METRIC_LABELS.get(k, k) for k in radar_keys]
        for i, m in enumerate(sel_methods):
            r_vals = [
                _get_val(m, k) / norm_base[k] if norm_base[k] else float("nan")
                for k in radar_keys
            ]
            fig.add_trace(go.Scatterpolar(
                r=r_vals + [r_vals[0]],
                theta=theta + [theta[0]],
                fill="toself", opacity=0.5, name=mlabel(m),
                line=dict(color=_method_color(m), width=2),
            ))

        fig.update_layout(
            polar=dict(radialaxis=dict(visible=True, tickformat=".2f")),
            title="Normalised metrics — lower = better on all axes (1.0 = mean across methods)",
            height=520,
            legend=dict(orientation="h", yanchor="bottom", y=-0.18),
        )
        st.plotly_chart(fig, use_container_width=True)
        st.caption(
            "Each axis normalised by mean across methods. "
            "temporal_corr* inverted (1−r) so all axes point the same direction."
        )

# ══════════════════════════════════════════════════════════════════════════════
# Tab 3 — Line plots (plotly, all methods on one figure)
# ══════════════════════════════════════════════════════════════════════════════
with tab_lines:
    has_plot_data = bool(plot_data)

    line_type = st.selectbox(
        "Plot type", ["seasonal", "annual", "cdf", "spectra"], key="ln_type",
    )
    sel_var_ln = st.selectbox("Variable", all_vars, key="ln_var")

    if has_plot_data:
        fig = go.Figure()

        if line_type == "seasonal":
            era5_done = False
            for m in sel_methods:
                d = plot_data.get(m, {}).get(sel_var_ln, {}).get("seasonal")
                if not d:
                    continue
                if not era5_done:
                    fig.add_trace(go.Scatter(
                        x=d["months"], y=d["era5"],
                        name="ERA5", line=dict(color="black", width=2.5),
                    ))
                    era5_done = True
                fig.add_trace(go.Scatter(
                    x=d["months"], y=d["pred"],
                    name=mlabel(m), line=dict(color=_method_color(m), width=2),
                ))
            fig.update_layout(
                title=f"Seasonal cycle — {sel_var_ln}",
                xaxis=dict(title="Month", tickvals=list(range(1, 13)),
                           ticktext=list("JFMAMJJASOND")),
                yaxis_title=sel_var_ln, height=430,
                legend=dict(orientation="h", yanchor="bottom", y=-0.28),
            )

        elif line_type == "annual":
            gcm_done = False
            for m in sel_methods:
                d = plot_data.get(m, {}).get(sel_var_ln, {}).get("annual")
                if not d:
                    continue
                if not gcm_done:
                    fig.add_trace(go.Scatter(
                        x=d["years"], y=d["gcm"],
                        name="GCM", line=dict(color="black", width=2.5),
                    ))
                    gcm_done = True
                years_pred = d.get("years_pred", d["years"])
                fig.add_trace(go.Scatter(
                    x=years_pred, y=d["pred"],
                    name=mlabel(m),
                    line=dict(color=_method_color(m), width=2, dash="dash"),
                ))
            fig.update_layout(
                title=f"Annual means — {sel_var_ln}",
                xaxis_title="Year", yaxis_title=sel_var_ln, height=430,
                legend=dict(orientation="h", yanchor="bottom", y=-0.28),
            )

        elif line_type == "cdf":
            era5_done = False
            for m in sel_methods:
                d = plot_data.get(m, {}).get(sel_var_ln, {}).get("cdf")
                if not d:
                    continue
                n_e, n_p = len(d["era5_x"]), len(d["pred_x"])
                if not era5_done:
                    fig.add_trace(go.Scatter(
                        x=d["era5_x"], y=np.linspace(0, 1, n_e).tolist(),
                        name="ERA5", line=dict(color="black", width=2.5),
                    ))
                    era5_done = True
                fig.add_trace(go.Scatter(
                    x=d["pred_x"], y=np.linspace(0, 1, n_p).tolist(),
                    name=mlabel(m), line=dict(color=_method_color(m), width=2),
                ))
            fig.update_layout(
                title=f"CDF — {sel_var_ln}",
                xaxis_title=sel_var_ln, yaxis_title="Cumulative probability",
                height=430,
                legend=dict(orientation="h", yanchor="bottom", y=-0.28),
            )

        elif line_type == "spectra":
            era5_done = False
            for m in sel_methods:
                sp = plot_data.get(m, {}).get(sel_var_ln, {}).get("spectra")
                if not sp or "k_centers_km_valid" not in sp:
                    continue
                k_km = sp["k_centers_km_valid"]
                if not era5_done:
                    fig.add_trace(go.Scatter(
                        x=k_km, y=sp["era5"],
                        name="ERA5", line=dict(color="black", width=2.5),
                    ))
                    era5_done = True
                fig.add_trace(go.Scatter(
                    x=k_km, y=sp["pred"],
                    name=mlabel(m), line=dict(color=_method_color(m), width=2),
                ))
            fig.update_layout(
                title=f"Isotropic spatial power spectrum — {sel_var_ln}",
                xaxis=dict(title="Spatial scale (km)", type="log", autorange="reversed"),
                yaxis=dict(title="PSD (a.u.)", type="log"),
                height=430,
                legend=dict(orientation="h", yanchor="bottom", y=-0.28),
            )

        if fig.data:
            st.plotly_chart(fig, use_container_width=True)
        else:
            st.info(f"No plot data for {sel_var_ln} / {line_type}. Re-run evaluate.py.")

    else:
        st.info(
            "**Interactive plots not yet available.**  \n"
            "Re-run `evaluate.py` with the updated script to generate `plot_data.json`. "
            "Showing static per-method PNGs for now."
        )
        type_to_prefix = {"seasonal": "seasonal", "annual": "annual", "cdf": "cdf"}
        prefix = type_to_prefix.get(line_type)
        if prefix:
            ncols = len(sel_methods)
            img_cols = st.columns(max(ncols, 1))
            for col, m in zip(img_cols, sel_methods):
                with col:
                    st.markdown(f"**{mlabel(m)}**")
                    img = RESULTS_DIR / m / "plots" / sel_var_ln / f"{prefix}_{sel_var_ln}.png"
                    if img.exists():
                        st.image(str(img))
                    else:
                        st.caption("No image")

# ══════════════════════════════════════════════════════════════════════════════
# Tab 4 — Spatial maps
# ══════════════════════════════════════════════════════════════════════════════
with tab_maps:
    col1, col2 = st.columns(2)
    with col1:
        plot_type = st.selectbox(
            "Plot type",
            ["bias_map", "temporal_corr", "autocorr", "annual", "cdf", "seasonal"],
            key="map_type",
        )
    with col2:
        sel_var_map = st.selectbox("Variable", all_vars, key="mv")

    ncols = len(sel_methods)
    plot_cols = st.columns(max(ncols, 1))
    for col, m in zip(plot_cols, sel_methods):
        with col:
            st.markdown(f"**{mlabel(m)}**")
            img = (RESULTS_DIR / m / "plots" / sel_var_map
                   / f"{plot_type}_{sel_var_map}.png")
            if img.exists():
                st.image(str(img))
            else:
                st.caption("No image — re-run evaluate.py to regenerate")

    if plot_type == "temporal_corr":
        st.caption(
            "These maps show **annual** temporal correlation after re-running evaluate.py. "
            "Existing maps were generated with daily correlation (trivially ≈1 everywhere). "
            "After re-run the colour scale auto-adjusts to the actual data range."
        )

# ══════════════════════════════════════════════════════════════════════════════
# Tab 5 — Inter-variable correlations
# ══════════════════════════════════════════════════════════════════════════════
with tab_intervar:
    st.subheader("Inter-variable correlation MAE (pred vs ERA5)")
    st.caption(
        "Mean absolute error of pointwise temporal correlation between variable pairs. "
        "Lower = better preservation of observed cross-variable dependencies."
    )

    # Scalar table (one column per method)
    intervar_rows = []
    for m in sel_methods:
        iv = raw_metrics[m].get("_intervar", {})
        if iv:
            intervar_rows.append({"Method": mlabel(m), **{k: round(v, 4) for k, v in iv.items()}})

    if intervar_rows:
        iv_df = pd.DataFrame(intervar_rows).set_index("Method")

        def _iv_style_col(col: pd.Series) -> list[str]:
            best = col.idxmin()
            return [
                "background-color: #c6efce; color: #276221; font-weight: bold"
                if idx == best else ""
                for idx in col.index
            ]

        st.dataframe(
            iv_df.style.apply(_iv_style_col, axis=0).format("{:.4f}"),
            use_container_width=True,
        )

        # Bar chart
        pairs = list(iv_df.columns)
        fig_iv = go.Figure()
        for m in sel_methods:
            lbl = mlabel(m)
            if lbl in iv_df.index:
                fig_iv.add_trace(go.Bar(
                    name=lbl, x=pairs,
                    y=[float(iv_df.loc[lbl, p]) if p in iv_df.columns else float("nan")
                       for p in pairs],
                    marker_color=_method_color(m),
                ))
        fig_iv.update_layout(
            barmode="group",
            title="Inter-variable correlation MAE by pair",
            yaxis_title="MAE of temporal correlation",
            height=370,
            legend=dict(orientation="h", yanchor="bottom", y=-0.35),
        )
        st.plotly_chart(fig_iv, use_container_width=True)
    else:
        st.info("No inter-variable scalar metrics found. Run evaluate.py first.")

    st.markdown("---")
    st.subheader("Pointwise correlation maps")
    st.caption(
        "Spatial maps of per-grid-point temporal correlation between variable pairs. "
        "After re-running evaluate.py, separate ERA5 / prediction / bias panels are saved."
    )

    # Discover available pairs
    all_pairs: list[str] = []
    for m in all_method_dirs:
        pdir = RESULTS_DIR / m / "plots"
        # Prefer separate panels (new-style)
        for p in sorted(pdir.glob("intervar_corr_*_*_era5.png")):
            parts = p.stem.split("_")
            pair = f"{parts[2]}_{parts[3]}"
            if pair not in all_pairs:
                all_pairs.append(pair)
        # Fall back to combined 3-panel PNG
        if not all_pairs:
            for p in sorted(pdir.glob("intervar_corr_*_*.png")):
                parts = p.stem.split("_")
                if len(parts) >= 4 and parts[-1] not in ("era5", "pred", "bias"):
                    pair = f"{parts[2]}_{parts[3]}"
                    if pair not in all_pairs:
                        all_pairs.append(pair)

    if not all_pairs:
        st.info("No inter-variable correlation maps found. Run evaluate.py first.")
    else:
        sel_pair = st.selectbox("Variable pair", all_pairs, key="iv_pair")
        v1, v2 = sel_pair.split("_", 1)

        # Check whether separate panels exist
        has_panels = any(
            (RESULTS_DIR / m / "plots" / f"intervar_corr_{v1}_{v2}_era5.png").exists()
            for m in all_method_dirs
        )

        if has_panels:
            panel_sel = st.radio(
                "Panel", ["ERA5 correlation", "Method prediction", "Bias (pred − ERA5)"],
                horizontal=True, key="iv_panel",
            )
            suffix = {"ERA5 correlation": "era5",
                      "Method prediction": "pred",
                      "Bias (pred − ERA5)": "bias"}[panel_sel]

            if suffix == "era5":
                # ERA5 is identical across methods — show once
                for m in all_method_dirs:
                    img = RESULTS_DIR / m / "plots" / f"intervar_corr_{v1}_{v2}_era5.png"
                    if img.exists():
                        st.markdown(f"**ERA5 r({v1}, {v2})**")
                        st.image(str(img))
                        break
            else:
                img_cols = st.columns(max(len(sel_methods), 1))
                for col, m in zip(img_cols, sel_methods):
                    with col:
                        st.markdown(f"**{mlabel(m)}**")
                        img = RESULTS_DIR / m / "plots" / f"intervar_corr_{v1}_{v2}_{suffix}.png"
                        if img.exists():
                            st.image(str(img))
                        else:
                            st.caption("No image — re-run evaluate.py")
        else:
            # Old-style: 3-panel combined PNGs, show all methods side by side
            img_cols = st.columns(max(len(sel_methods), 1))
            for col, m in zip(img_cols, sel_methods):
                with col:
                    st.markdown(f"**{mlabel(m)}**")
                    img = RESULTS_DIR / m / "plots" / f"intervar_corr_{v1}_{v2}.png"
                    if img.exists():
                        st.image(str(img))
                    else:
                        st.caption("No image")
