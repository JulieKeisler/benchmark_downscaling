#!/usr/bin/env python3
"""Recompute extreme-frequency / extreme-intensity bias as ABS values (per
grid point, as in scalar_metrics_era5.py) from saved predictions.pt + ERA5, and
patch the existing metrics.json files in place.

Only the two extreme_* vs_obs keys are replaced; every other metric is kept.
Methods without predictions.pt are skipped (must be regenerated by evaluate.py).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE.parent / "src"))
sys.path.insert(0, str(_HERE.parent / "src" / "evaluation"))

import numpy as np
import pandas as pd
import xarray as xr

from evaluation.data_processing import load_era5, load_predictions
from metrics.scalar_metrics_era5 import extreme_freq_bias, extreme_intensity_bias


def align_pair(a: xr.DataArray, b: xr.DataArray) -> tuple:
    """Align onto the shared calendar days, ignoring time-of-day.

    Some inference scripts save daily timestamps at 12:00 (GCM-derived) rather
    than ERA5's 00:00; index both sides by (normalized) date so they match.
    """
    ta = pd.to_datetime(a.time.values).normalize().values
    tb = pd.to_datetime(b.time.values).normalize().values
    common = np.intersect1d(ta, tb)
    if len(common) == 0:
        return None, None
    ia = np.isin(ta, common)
    ib = np.isin(tb, common)
    return a.isel(time=ia), b.isel(time=ib)


def patch_metrics(mdir: Path, era5_dir: Path, variables: list[str]) -> int:
    metrics_file = mdir / "metrics.json"
    if not metrics_file.exists():
        return -1
    try:
        preds = load_predictions(mdir, variables)
    except (FileNotFoundError, ValueError):
        return -1
    if not preds:
        return -2
    with open(metrics_file) as f:
        data = json.load(f)
    n_upd = 0
    for var in variables:
        if var not in data:
            continue
        obs = load_era5(era5_dir, var, 2000, 2020)
        if obs is None:
            continue
        o, p = align_pair(obs, preds.get(var))
        if o is None:
            continue
        if "vs_obs" not in data[var]:
            data[var]["vs_obs"] = {}
        try:
            data[var]["vs_obs"]["extreme_freq"] = extreme_freq_bias(o, p, q=0.95)
            data[var]["vs_obs"]["extreme_intensity"] = extreme_intensity_bias(o, p, q=0.95)
        except Exception:
            continue
        n_upd += 1
    if n_upd:
        with open(metrics_file, "w") as f:
            json.dump(data, f, indent=2)
    return n_upd


REGIONS = ["france", "australia", "us_central"]
ALL_VARS = ["tas", "pr", "psl", "sfcWind", "sfcWindmax", "rsds"]


def main() -> int:
    root = Path(__file__).resolve().parent.parent / "results"
    if len(sys.argv) > 1:
        root = Path(sys.argv[1])
    # Patch a single method dir directly (avoid holding many predictions in RAM).
    # Usage: recompute_extremes.py <root> <region/methoddir> [region] [era5-dir]
    #   region defaults to the method dir's parent name.
    if len(sys.argv) > 2:
        mdir = root / sys.argv[2]
        region = sys.argv[3] if len(sys.argv) > 3 else mdir.parent.name
        era5 = Path(sys.argv[4]) if len(sys.argv) > 4 else (
            root.parent / "data" / "era5" if region == "france"
            else root.parent / "data" / "era5" / region)
        n = patch_metrics(mdir, era5, ALL_VARS)
        print(f"{mdir}: updated extreme_* for {n} vars")
        return 0
    for region in REGIONS:
        era5 = root.parent / "data" / "era5" if region == "france" \
            else root.parent / "data" / "era5" / region
        if not era5.is_dir():
            print(f"skip {region}: era5 dir {era5} not found")
            continue
        for m in sorted(p for p in (root / region).iterdir() if p.is_dir()):
            n = patch_metrics(m, era5, ALL_VARS)
            if n and n > 0:
                print(f"{region}/{m.name}: updated extreme_* for {n} vars")
    return 0


if __name__ == "__main__":
    sys.exit(main())